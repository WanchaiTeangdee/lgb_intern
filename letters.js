/* =====================================================================
   letters.js — จดหมายถึงพี่แต่ละคน (ตี๋กับหมวยเขียนแยกกัน คนละช่อง)
   ---------------------------------------------------------------------
   แต่ละฉบับมี 2 ช่อง
     text  : ข้อความจดหมาย — พิมพ์ระหว่างเครื่องหมาย ` ` (backtick)
             เว้นบรรทัดว่าง 1 บรรทัด = ขึ้นย่อหน้าใหม่ (ห้ามใช้ ` ในข้อความ)
     media : รูป/คลิปที่แนบท้ายจดหมาย ใส่กี่อันก็ได้ (ไม่มีก็ปล่อย [] ไว้)
               "media/natto-tee-1.jpg"                ← รูป (.jpg .png .webp)
               "media/natto-tee-clip.mp4"             ← คลิป (.mp4 แนะนำที่สุด)
               "https://youtu.be/xxxxxxxxxxx"         ← คลิปจาก YouTube (ตั้งเป็น Unlisted ได้)
               { src: "media/a.jpg", caption: "..." } ← ใส่คำบรรยายเฉพาะรูปนี้

   • ช่องไหนทั้ง text และ media ว่างอยู่ จะไม่แสดงบนเว็บ
     (เช่น ถ้ามีแค่ตี๋เขียนถึงพี่คนนี้ ก็ปล่อยช่องของหมวยว่างไว้)
   • ใส่แค่รูปไม่มีข้อความก็ได้ — ใส่แค่ข้อความไม่มีรูปก็ได้
   • อยากเขียนฉบับเดียวร่วมกัน ให้เปลี่ยนชื่อเป็น "น้องตี๋ & น้องหมวย" แล้วลบอีกช่องออก
   • ถ้าไม่ต้องใช้รูป/คลิป เขียนแบบสั้นก็ได้ เช่น  "น้องตี๋": `ข้อความ`,

   ไฟล์รูป/คลิปวางไว้ในโฟลเดอร์ media/
   • ชื่อไฟล์เป็นภาษาอังกฤษ ไม่มีเว้นวรรค (แนะนำ ชื่อพี่-ชื่อเรา-เลข เช่น natto-tee-1.jpg)
   • คลิปจาก iPhone (.mov) บางเครื่องเปิดไม่ได้ → แปลงเป็น .mp4 ก่อน
   • คลิปไฟล์ใหญ่ (เกิน ~50MB) แนะนำอัปขึ้น YouTube แบบ Unlisted แล้วใส่ลิงก์แทน

   ไอเดียสิ่งที่จะเขียน
   1. ความประทับใจแรก / วันแรกที่เจอพี่
   2. เรื่องที่พี่สอนหรือช่วยเหลือ แล้วจำได้ไม่ลืม
   3. โมเมนต์ตลกๆ หรือมุกประจำของพี่
   4. สิ่งที่อยากขอบคุณ
   5. คำอวยพร / สิ่งที่อยากบอกก่อนจากกัน

   ตัวอย่างที่เขียนเสร็จแล้ว
   LETTERS.natto = {
     "น้องตี๋": {
       text: `
   ขอบคุณพี่นัตโตะที่สอนผมตั้งแต่วันแรกที่ยังทำอะไรไม่เป็นเลย

   จำได้ว่าตอนส่งงานชิ้นแรก พี่นั่งอธิบายให้ทีละข้อจนเข้าใจ
   `,
       media: ["media/natto-tee-1.jpg", "media/natto-tee-clip.mp4"],
     },
     "น้องหมวย": {
       text: `ขอบคุณพี่นัตโตะมากๆ ค่ะ`,
       media: [],
     },
   };
   ===================================================================== */

